create or replace function public.mingshen_purge_expired_diagnostics()
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
  delete from public.mingshen_telemetry_events
  where created_at < now() - interval '30 days';

  delete from public.mingshen_crash_reports
  where created_at < now() - interval '30 days';
$$;

revoke all on function public.mingshen_purge_expired_diagnostics() from public;

