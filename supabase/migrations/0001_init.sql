-- Mingshen Harness: public update channel and opt-in diagnostics
-- Run this file manually in the Supabase SQL editor as the project owner.
-- Then run 0003_zip_updates.sql for verified ZIP updates in version 1.2.6+.
--
-- Security model:
--   * Anonymous clients can call mingshen_get_latest_release() and receive at most one row.
--   * Anonymous clients cannot read, update, or delete mingshen_app_releases directly.
--   * Anonymous clients can submit only the constrained diagnostic RPCs.
--   * Anonymous clients cannot read any diagnostic table.

begin;

create table if not exists public.mingshen_app_releases (
  id bigint generated by default as identity primary key,
  version text not null,
  download_page_url text not null,
  notes text not null default '',
  published_at timestamptz not null default now(),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint mingshen_app_releases_version_format
    check (version ~ '^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$'),
  constraint mingshen_app_releases_download_page_https
    check (download_page_url ~* '^https://'),
  constraint mingshen_app_releases_download_page_length
    check (char_length(download_page_url) <= 2048),
  constraint mingshen_app_releases_notes_length
    check (char_length(notes) <= 1000)
);

-- create table if not exists does not evolve an older deployment of the table.
-- Keep this repair block so an existing release table can be upgraded in place.
alter table public.mingshen_app_releases
  add column if not exists download_page_url text not null
    default 'https://example.invalid/mingshen-release',
  add column if not exists notes text not null default '',
  add column if not exists published_at timestamptz not null default now(),
  add column if not exists is_active boolean not null default true,
  add column if not exists created_at timestamptz not null default now();

create unique index if not exists mingshen_app_releases_version_unique
  on public.mingshen_app_releases (version);

create index if not exists mingshen_app_releases_latest_lookup
  on public.mingshen_app_releases (is_active, published_at desc);

alter table public.mingshen_app_releases enable row level security;

-- Deliberately no table policy. The release table is not client-readable.
revoke all on table public.mingshen_app_releases from anon, authenticated;

create or replace function public.mingshen_get_latest_release()
returns table (
  version text,
  download_page_url text,
  notes text,
  published_at timestamptz
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select
    r.version,
    r.download_page_url,
    r.notes,
    r.published_at
  from public.mingshen_app_releases as r
  where r.is_active = true
    and r.published_at <= now()
  order by
    string_to_array(r.version, '.')::int[] desc,
    r.published_at desc
  limit 1;
$$;

revoke all on function public.mingshen_get_latest_release() from public;
grant execute on function public.mingshen_get_latest_release() to anon, authenticated;

create table if not exists public.mingshen_telemetry_events (
  id uuid primary key default gen_random_uuid(),
  client_event_id uuid not null unique,
  install_id uuid not null,
  app_version text not null,
  event_type text not null,
  severity text not null,
  module text not null default 'unknown',
  error_code text,
  diagnostic_summary text not null default '',
  redacted_stack text not null default '',
  os_version text not null default '',
  locale text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint mingshen_telemetry_events_app_version_format
    check (app_version ~ '^[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}$'),
  constraint mingshen_telemetry_events_event_type_length
    check (char_length(event_type) between 1 and 64),
  constraint mingshen_telemetry_events_severity
    check (severity in ('info', 'warning', 'error', 'fatal')),
  constraint mingshen_telemetry_events_module_length
    check (char_length(module) between 1 and 64),
  constraint mingshen_telemetry_events_error_code_length
    check (error_code is null or char_length(error_code) <= 64),
  constraint mingshen_telemetry_events_summary_length
    check (char_length(diagnostic_summary) <= 1000),
  constraint mingshen_telemetry_events_stack_length
    check (char_length(redacted_stack) <= 12000),
  constraint mingshen_telemetry_events_os_version_length
    check (char_length(os_version) <= 128),
  constraint mingshen_telemetry_events_locale_length
    check (char_length(locale) <= 32),
  constraint mingshen_telemetry_events_metadata_size
    check (octet_length(metadata::text) <= 4096)
);

create index if not exists mingshen_telemetry_events_created_at_idx
  on public.mingshen_telemetry_events (created_at);

alter table public.mingshen_telemetry_events enable row level security;
revoke all on table public.mingshen_telemetry_events from anon, authenticated;

create or replace function public.mingshen_submit_telemetry(
  p_client_event_id uuid,
  p_install_id uuid,
  p_app_version text,
  p_event_type text,
  p_severity text,
  p_module text,
  p_error_code text,
  p_diagnostic_summary text,
  p_redacted_stack text,
  p_os_version text,
  p_locale text,
  p_metadata jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  inserted_id uuid;
  forbidden_key text;
begin
  if p_metadata is null or jsonb_typeof(p_metadata) <> 'object' then
    raise exception 'metadata must be a JSON object';
  end if;

  if octet_length(p_metadata::text) > 4096 then
    raise exception 'metadata is too large';
  end if;

  select key
    into forbidden_key
  from jsonb_object_keys(p_metadata) as key
  where key not in (
    'error_family',
    'module',
    'os_build',
    'arch',
    'locale',
    'feature',
    'tool',
    'http_status',
    'duration_ms'
  )
  limit 1;

  if forbidden_key is not null then
    raise exception 'metadata key is not allowed: %', forbidden_key;
  end if;

  insert into public.mingshen_telemetry_events (
    client_event_id,
    install_id,
    app_version,
    event_type,
    severity,
    module,
    error_code,
    diagnostic_summary,
    redacted_stack,
    os_version,
    locale,
    metadata
  )
  values (
    p_client_event_id,
    p_install_id,
    p_app_version,
    p_event_type,
    p_severity,
    p_module,
    p_error_code,
    left(coalesce(p_diagnostic_summary, ''), 1000),
    left(coalesce(p_redacted_stack, ''), 12000),
    left(coalesce(p_os_version, ''), 128),
    left(coalesce(p_locale, ''), 32),
    p_metadata
  )
  on conflict (client_event_id) do nothing
  returning id into inserted_id;

  return inserted_id;
end;
$$;

revoke all on function public.mingshen_submit_telemetry(
  uuid, uuid, text, text, text, text, text, text, text, text, text, jsonb
) from public;
grant execute on function public.mingshen_submit_telemetry(
  uuid, uuid, text, text, text, text, text, text, text, text, text, jsonb
) to anon, authenticated;

